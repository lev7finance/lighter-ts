describe("backoff arithmetic", () => {
  test("full jitter, exponential, capped", () => {
    const policy = { baseMs: 200, capMs: 5_000 };
    // random() === 1 is the top of each window, which is what makes the growth visible.
    expect(retryDelayMs(0, policy, undefined, () => 1)).toBe(200);
    expect(retryDelayMs(1, policy, undefined, () => 1)).toBe(400);
    expect(retryDelayMs(2, policy, undefined, () => 1)).toBe(800);
    expect(retryDelayMs(9, policy, undefined, () => 1)).toBe(5_000);
    // Full jitter: the whole window is in play, not a fixed delay plus noise.
    expect(retryDelayMs(3, policy, undefined, () => 0)).toBe(0);
    expect(retryDelayMs(3, policy, undefined, () => 0.5)).toBe(800);
  });

  test("Retry-After wins over the computed delay, clamped to the cap", () => {
    const policy = { baseMs: 200, capMs: 5_000 };
    expect(retryDelayMs(0, policy, 1_000, () => 1)).toBe(1_000);
    expect(retryDelayMs(0, policy, 120_000, () => 1)).toBe(5_000);
  });

  test("Retry-After parses both RFC forms and shrugs off anything else", () => {
    expect(parseRetryAfterMs("2", 0)).toBe(2_000);
    expect(parseRetryAfterMs("0", 0)).toBe(0);
    expect(parseRetryAfterMs(null, 0)).toBeUndefined();
    expect(parseRetryAfterMs("soon", 0)).toBeUndefined();
    expect(parseRetryAfterMs("", 0)).toBeUndefined();
    const now: number = Date.parse("Wed, 21 Oct 2015 07:28:00 GMT");
    expect(parseRetryAfterMs("Wed, 21 Oct 2015 07:28:03 GMT", now)).toBe(3_000);
    expect(parseRetryAfterMs("Wed, 21 Oct 2015 07:27:00 GMT", now)).toBe(0);
  });

  test("only 429 and 5xx are worth repeating", () => {
    expect(isRetryableStatus(429)).toBe(true);
    expect(isRetryableStatus(500)).toBe(true);
    expect(isRetryableStatus(503)).toBe(true);
    expect(isRetryableStatus(400)).toBe(false);
    expect(isRetryableStatus(401)).toBe(false);
    expect(isRetryableStatus(403)).toBe(false);
    expect(isRetryableStatus(200)).toBe(false);
  });
});

