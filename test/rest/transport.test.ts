describe("query serialisation", () => {
  test("undefined and null keys are omitted entirely, not sent empty", () => {
    // Several endpoints treat an empty string differently from an absent key.
    const q = buildQuery({ market_id: 1, cursor: undefined, filter: null, limit: 5 });
    expect(q.toString()).toBe("market_id=1&limit=5");
    expect(q.has("cursor")).toBe(false);
    expect(q.has("filter")).toBe(false);
  });

  test("booleans are the lowercase literals", () => {
    expect(buildQuery({ a: true, b: false }).toString()).toBe("a=true&b=false");
  });

  test("numbers are plain decimal; bigints are exact", () => {
    expect(buildQuery({ n: 0, m: -7, f: 1.5 }).toString()).toBe("n=0&m=-7&f=1.5");
    expect(buildQuery({ big: 281474976710654n }).toString()).toBe("big=281474976710654");
    expect(buildQuery({ big: 9007199254740993n }).toString()).toBe("big=9007199254740993");
  });

  test("a number that would serialise in exponent form is refused, not sent", () => {
    // `String(5e21)` is "5e+21", which the server rejects as an invalid param.
    expect(() => buildQuery({ v: 5e21 })).toThrow(LighterValidationError);
    expect(() => buildQuery({ v: 1e-7 })).toThrow(LighterValidationError);
    expect(() => buildQuery({ v: 2 ** 53 })).toThrow(LighterValidationError);
    expect(() => buildQuery({ v: Number.NaN })).toThrow(LighterValidationError);
    expect(() => buildQuery({ v: Number.POSITIVE_INFINITY })).toThrow(LighterValidationError);
    try {
      buildQuery({ v: 5e21 });
    } catch (e: unknown) {
      expect((e as LighterValidationError).code).toBe("UNSAFE_INTEGER");
      expect((e as LighterValidationError).field).toBe("v");
    }
  });

  test("a structured value is refused: those travel as JSON strings in a single field", () => {
    expect(() => buildQuery({ v: { a: 1 } })).toThrow(LighterValidationError);
    expect(() => buildQuery({ v: [[1]] })).toThrow(LighterValidationError);
  });

  test("the two repeat-key array params emit repeated keys", () => {
    // `accountTxs.types` and `transfer/history.type` — the only two, both `style=form,explode=true`.
    const txs = buildUrl(route["accountTxs"] as RouteDef, { by: "account_index", value: "1", limit: 10, types: [14, 15] }, MAINNET);
    expect(txs).toBe(
      "https://mainnet.zklighter.elliot.ai/api/v1/accountTxs?by=account_index&value=1&limit=10&types=14&types=15",
    );

    const transfers = buildUrl(
      route["transferHistory"] as RouteDef,
      { account_index: 1, type: ["L2Transfer", "L2MintShares"] },
      MAINNET,
    );
    expect(transfers).toBe(
      "https://mainnet.zklighter.elliot.ai/api/v1/transfer/history?account_index=1&type=L2Transfer&type=L2MintShares",
    );

    expect(buildQuery({ types: [] }).toString()).toBe("");
  });

  test("the colons in a real auth token percent-encode and round-trip through URL", () => {
    const url: string = buildUrl(route["orderBooks"] as RouteDef, undefined, MAINNET, { auth: TOKEN });
    expect(TOKEN.split(":")).toHaveLength(4);
    expect(url).toContain("auth=");
    expect(url).not.toContain(`auth=${TOKEN}`); // the colons must be escaped
    expect(url).toContain("%3A");
    expect(new URL(url).searchParams.get("auth")).toBe(TOKEN);
  });
});

