interface RecordedCall {
  readonly url: string;
  readonly method: string;
  readonly headers: Record<string, string>;
  readonly body: string | undefined;
  readonly signal: AbortSignal | undefined;
}

interface Stub {
  readonly fetch: typeof globalThis.fetch;
  readonly calls: RecordedCall[];
}

type Responder = (call: RecordedCall, index: number) => Response | Promise<Response>;

/** An injected `fetch` that records every call and answers from `responder`. */
function stubFetch(responder: Responder): Stub {
  const calls: RecordedCall[] = [];
  const fetchImpl = ((input: unknown, init?: RequestInit): Promise<Response> => {
    const headers: Record<string, string> = {};
    const raw: unknown = init?.headers;
    if (raw !== undefined && raw !== null) {
      for (const key of Object.keys(raw as Record<string, string>)) {
        headers[key] = (raw as Record<string, string>)[key] as string;
      }
    }
    const call: RecordedCall = {
      url: String(input),
      method: init?.method ?? "GET",
      headers,
      body: typeof init?.body === "string" ? init.body : undefined,
      signal: init?.signal ?? undefined,
    };
    calls.push(call);
    return Promise.resolve(responder(call, calls.length - 1)).then((r: Response): Response => r);
  }) as unknown as typeof globalThis.fetch;
  return { fetch: fetchImpl, calls };
}

/** A stub that replays a fixed script of responses, one per call. */
function scripted(...responses: readonly (() => Response)[]): Stub {
  return stubFetch((_call, index): Response => {
    const make: (() => Response) | undefined = responses[index];
    if (make === undefined) throw new Error(`unexpected call #${String(index + 1)}`);
    return make();
  });
}

function json(body: unknown, status: number = 200, headers: Record<string, string> = {}): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json; charset=utf-8", ...headers },
  });
}

function text(body: string, status: number, headers: Record<string, string> = {}): Response {
  return new Response(body, { status, headers: { "content-type": "text/html", ...headers } });
}

/** Backoff sleeps, captured instead of slept. */
function fakeSleep(): { sleep: (ms: number) => Promise<void>; delays: number[] } {
  const delays: number[] = [];
  return {
    sleep: (ms: number): Promise<void> => {
      delays.push(ms);
      return Promise.resolve();
    },
    delays,
  };
}

type Mutable = Record<string, unknown>;
const g: Mutable = globalThis as unknown as Mutable;

/**
 * Run `body` with browser-shaped globals installed.
 *
 * `request()` resolves its config **synchronously**, before its first `await`, so calling it inside
 * this block is enough to pin the environment; the returned promise is awaited outside, with the
 * globals already restored.
 */
function withGlobals<T>(entries: Record<string, unknown>, body: () => T): T {
  const saved = new Map<string, { had: boolean; value: unknown }>();
  for (const key of Object.keys(entries)) {
    saved.set(key, { had: key in g, value: g[key] });
    g[key] = entries[key];
  }
  try {
    return body();
  } finally {
    for (const [key, previous] of saved) {
      if (previous.had) g[key] = previous.value;
      else delete g[key];
    }
  }
}

